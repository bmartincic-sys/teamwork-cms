#!/usr/bin/env node
/* build-redirects.js - turn redirect-map.csv into Netlify's _redirects file.
 *
 * Runs at the start of `npm run build` and writes src/_redirects, which Eleventy copies
 * into the publish folder. The CSV is the thing to edit; this file just translates it.
 *
 * What it emits, in order (Netlify takes the first matching rule):
 *   1. one 301 per CSV row whose old and new paths differ, except rows netlify.toml
 *      already covers (those keep living there)
 *   2. a short tail of WordPress-era catch-alls: Yoast sitemaps, category / tag / author
 *      archives and blog pagination, which the old sitemaps never listed
 *
 * Trailing slashes: Netlify matches a rule for /old/ against /old as well, so one rule
 * per path is enough. Rows with the same old and new path need no rule and are skipped.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const CSV = path.join(__dirname, 'redirect-map.csv');
const TOML = path.join(ROOT, 'netlify.toml');
const OUT = path.join(ROOT, 'src', '_redirects');

function parseCsv(text) {
  const rows = [];
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim()) continue;
    const cells = []; let cur = ''; let q = false;
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      if (q) { if (c === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (c === '"') q = false; else cur += c; }
      else if (c === '"') q = true; else if (c === ',') { cells.push(cur); cur = ''; } else cur += c;
    }
    cells.push(cur); rows.push(cells);
  }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] || ''])));
}

const norm = (p) => (p.startsWith('http') ? p : (p.endsWith('/') || p.includes('#') || /\.\w+$/.test(p) ? p : p + '/'));

// paths netlify.toml already redirects, with and without the trailing slash
const inToml = new Set();
for (const m of fs.readFileSync(TOML, 'utf8').matchAll(/from\s*=\s*"([^"]+)"/g)) {
  inToml.add(m[1]); inToml.add(m[1].replace(/\/$/, ''));
}

const rows = parseCsv(fs.readFileSync(CSV, 'utf8'));
const seen = new Set(); const lines = []; let skippedSame = 0, skippedToml = 0, problems = [];
for (const r of rows) {
  const from = norm(r.old_path.trim()); const to = norm(r.new_path.trim());
  if (!from.startsWith('/')) { problems.push(`bad old_path: ${r.old_path}`); continue; }
  if (!to.startsWith('/') && !to.startsWith('http')) { problems.push(`bad new_path for ${from}: ${r.new_path}`); continue; }
  if (from === to) { skippedSame++; continue; }
  if (inToml.has(from) || inToml.has(from.replace(/\/$/, ''))) { skippedToml++; continue; }
  if (seen.has(from)) { problems.push(`duplicate old_path: ${from}`); continue; }
  seen.add(from);
  lines.push(`${from}  ${to}  301`);
}

// WordPress leftovers the sitemaps never listed. Splats last, so specific rows win.
const tail = [
  ['/sitemap_index.xml', '/sitemap.xml'],
  ['/post-sitemap.xml', '/sitemap.xml'],
  ['/page-sitemap.xml', '/sitemap.xml'],
  ['/category-sitemap.xml', '/sitemap.xml'],
  ['/feed/', '/blog/'],
  ['/blog/feed/', '/blog/'],
  ['/category/*', '/blog/'],
  ['/tag/*', '/blog/'],
  ['/author/*', '/blog/'],
  ['/page/*', '/blog/'],
  ['/blog/page/*', '/blog/'],
];
for (const [from, to] of tail) if (!seen.has(from)) { seen.add(from); lines.push(`${from}  ${to}  301`); }

if (problems.length) {
  console.error('[redirects] problems in redirect-map.csv:'); problems.forEach((p) => console.error('  ' + p));
  process.exit(1);
}

const header = [
  '# Generated by tools/redirects/build-redirects.js from tools/redirects/redirect-map.csv.',
  '# Do not edit by hand: change the CSV (or netlify.toml for site-structure redirects) and rebuild.',
  `# ${lines.length - tail.length} rules from the map, ${tail.length} WordPress catch-alls.`,
  '',
];
fs.writeFileSync(OUT, header.concat(lines).join('\n') + '\n');
console.log(`[redirects] ${lines.length} rules -> src/_redirects (${skippedSame} same-path rows skipped, ${skippedToml} already in netlify.toml)`);
